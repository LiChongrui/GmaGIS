def draw_world(painter, rect, land_brush, edge_pen=None,
               graticule_pen=None, graticule_step=30,
               sea_brush=None, emph_pen=None,
               land_rings=None, hole_rings=None):
    from PySide6.QtCore import QPointF
    from PySide6.QtGui import QPainterPath, QPolygonF

    x0, y0 = rect.left(), rect.top()
    w, h = rect.width(), rect.height()
    if w <= 1 or h <= 1:
        return

    def to_px(lon, lat):
        return QPointF(x0 + (lon + 180.0) / 360.0 * w,
                       y0 + (90.0 - lat) / 180.0 * h)

    if graticule_pen is not None and graticule_step and graticule_step > 0:
        painter.setPen(graticule_pen)
        lon = -180
        while lon <= 180:
            painter.drawLine(to_px(lon, 90), to_px(lon, -90))
            lon += graticule_step
        lat = -60
        while lat <= 60:
            painter.drawLine(to_px(-180, lat), to_px(180, lat))
            lat += graticule_step

    if emph_pen is not None:
        painter.setPen(emph_pen)
        painter.drawLine(to_px(-180, 0), to_px(180, 0))
        painter.drawLine(to_px(0, 90), to_px(0, -90))

    def _fill(ring, brush, pen):
        poly = QPolygonF([to_px(lon, lat) for lon, lat in ring])
        path = QPainterPath()
        path.addPolygon(poly)
        path.closeSubpath()
        if brush is not None:
            painter.setBrush(brush)
            painter.setPen(pen if pen is not None else brush)
            painter.drawPath(path)

    painter.setPen(edge_pen if edge_pen is not None else land_brush)
    painter.setBrush(land_brush)
    if land_rings is None:
        land_rings = WORLD_LAND
        if hole_rings is None:
            hole_rings = WORLD_HOLES
    for ring in land_rings:
        _fill(ring, land_brush, edge_pen)
    if sea_brush is not None:
        for ring in (hole_rings or []):
            _fill(ring, sea_brush, None)


def draw_extent(painter, rect, west, south, east, north,
                fill, pen, min_span=1.0):
    from PySide6.QtCore import QPointF, QRectF, Qt
    from PySide6.QtGui import QPainterPath

    x0, y0 = rect.left(), rect.top()
    w, h = rect.width(), rect.height()
    if w <= 1 or h <= 1:
        return

    def px(lon, lat):
        return QPointF(x0 + (lon + 180.0) / 360.0 * w,
                       y0 + (90.0 - lat) / 180.0 * h)

    if east < west:
        west, east = east, west
    if east - west < min_span:
        c = (east + west) / 2.0
        west, east = c - min_span / 2.0, c + min_span / 2.0
    if north - south < min_span:
        c = (north + south) / 2.0
        south, north = c - min_span / 2.0, c + min_span / 2.0
    west = max(-180.0, west)
    east = min(180.0, east)
    south = max(-90.0, south)
    north = min(90.0, north)

    if west <= -179.9 and east >= 179.9 and south <= -89.9 and north >= 89.9:
        inset = max(3.0, min(w, h) * 0.02)
        rr = rect.adjusted(inset, inset, -inset, -inset)
        painter.save()
        try:
            painter.setPen(pen)
            painter.setBrush(Qt.BrushStyle.NoBrush)
            painter.drawRect(rr)
        finally:
            painter.restore()
        return

    path = QPainterPath()
    path.addRect(QRectF(px(west, north), px(east, south)).normalized())
    painter.save()
    try:
        painter.setPen(pen)
        painter.setBrush(fill)
        painter.drawPath(path)
    finally:
        painter.restore()
